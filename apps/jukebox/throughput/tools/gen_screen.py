#!/usr/bin/env python3
"""Write the test ROM's tiles, palette and the screen it comes up with, and
where on that screen the ROM writes.

    tools/gen_screen.py build
    tools/gen_screen.py build --preview screen.png

The tiles are the jukebox's (../tools/gen_ui.py): its 5 x 7 font with each
character at its ASCII code, its palettes, and its header, the name in the
big letters over the credit line, with what this ROM is between the two in
the credit line's blue. The font has capitals only.

Under the header is a line for what the test is doing, and a half of the
screen for each direction: its title, and a row for each of ROWS. screen.bin
is the nametable and its attributes with all of that on it and no figures;
screen.inc tells the ROM where the figures go.
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))

import gen_ui  # noqa: E402

# The header is the jukebox's but for the word under the name.
LOGO_ROW, LOGO_TEXT = gen_ui.LOGO_ROW, gen_ui.LOGO_TEXT
SUBTITLE_ROW, SUBTITLE_ROWS = gen_ui.SUBTITLE_ROW, gen_ui.SUBTITLE_ROWS
SUBTITLE = "THROUGHPUT TEST"
CREDIT_ROW = gen_ui.CREDIT_ROW
LOGO_LAST_ROW = gen_ui.LOGO_LAST_ROW

# Text is 28 columns wide from LEFT. A direction has a title row and, under
# it, a row for each of ROWS: its name, and a value of up to so many tiles.
LEFT = 2
WIDTH = 28
STATE_ROW = 9
WAITING = "WAITING FOR THE NESP32"
ROWS = (("STATUS", 8), ("SPEED", 10), ("SENT", 10), ("BAD", 10), ("CPU", 4),
        ("FASTEST", 13), ("FAILED", 19))
VALUE_COLUMN = LEFT + 9
HALVES = (("NESP32 TO NES", 11), ("NES TO NESP32", 20))     # title, its row
LAST_ROW = 27                       # rows 28 and 29 are overscan


def build_screen():
    screen = gen_ui.Screen()
    screen.names[:] = b" " * len(screen.names)  # the ROM writes text over text
    gen_ui.header(screen, SUBTITLE)
    screen.text(LEFT, STATE_ROW, WAITING)
    for title, top in HALVES:
        screen.text(LEFT, top, title)
        for index, (name, _) in enumerate(ROWS):
            screen.text(LEFT + 1, top + 1 + index, name)
    return screen


def palette_data():
    data = bytearray()
    for colors in gen_ui.PALETTES:
        data += bytes((gen_ui.BACKDROP,) + colors)
    return bytes(data)


def screen_include():
    assert all(len(name) + 2 <= VALUE_COLUMN - LEFT and VALUE_COLUMN + width <= LEFT + WIDTH
               for name, width in ROWS)
    assert all(top + len(ROWS) <= LAST_ROW for _, top in HALVES)
    lines = ["; Generated by tools/gen_screen.py. Do not edit.", "",
             "STATE_ROW = %d" % STATE_ROW, "STATE_COLUMN = %d" % LEFT,
             "STATE_WIDTH = %d" % WIDTH, "VALUE_COLUMN = %d" % VALUE_COLUMN,
             "HALF_RX = %d           ; a direction's title row; its values are under it"
             % HALVES[0][1],
             "HALF_TX = %d" % HALVES[1][1]]
    for index, (name, width) in enumerate(ROWS):
        lines += ["ROW_%s = %d" % (name, index + 1), "WIDTH_%s = %d" % (name, width)]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("out_dir", help="directory for chr.bin, screen.bin, palette.bin "
                                        "and screen.inc")
    parser.add_argument("--preview", help="also write the opening screen as a PNG")
    args = parser.parse_args(argv)
    screen = build_screen()
    os.makedirs(args.out_dir, exist_ok=True)
    gen_ui.write_if_changed(os.path.join(args.out_dir, "chr.bin"), screen.chr())
    gen_ui.write_if_changed(os.path.join(args.out_dir, "screen.bin"), screen.nametable())
    gen_ui.write_if_changed(os.path.join(args.out_dir, "palette.bin"), palette_data())
    gen_ui.write_if_changed(os.path.join(args.out_dir, "screen.inc"),
                            screen_include().encode())
    if args.preview:
        gen_ui.write_png(args.preview, gen_ui.render(screen.chr(), screen.nametable()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
