#!/usr/bin/env python3
"""Write the CRC-16/CCITT-FALSE lookup tables the NES uses to check bursts.

    tools/gen_crc_table.py build/crc16_table.inc

Two 256-byte tables, high and low bytes of T[i], where T[i] is the CRC
register after shifting i << 8 through eight rounds. Per byte the NES does
index = crc_hi ^ byte; crc_hi = crc_lo ^ hi[index]; crc_lo = lo[index].
"""

import sys


def table():
    entries = []
    for index in range(256):
        crc = index << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else crc << 1
            crc &= 0xFFFF
        entries.append(crc)
    return entries


def main(argv):
    entries = table()
    lines = ["; Generated by tools/gen_crc_table.py. Do not edit."]
    for name, part in (("crc_table_hi", lambda v: v >> 8), ("crc_table_lo", lambda v: v & 0xFF)):
        lines.append("%s:" % name)
        for row in range(0, 256, 16):
            values = ", ".join("$%02X" % part(v) for v in entries[row:row + 16])
            lines.append("    .byte %s" % values)
    with open(argv[1], "w") as handle:
        handle.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
