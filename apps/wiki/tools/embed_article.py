#!/usr/bin/env python3
"""Lay a text file out as the standalone ROM's built-in article.

    tools/embed_article.py nes/demo_article.txt build

Writes article.bin, lines of COLUMNS tile numbers exactly as the Stick
would serve them, and article.inc with their count. The file's first line
is the article's title; the rest is laid out by the Stick's own code
(nesp32's, through stick.py), with "== Heading ==" lines for headings.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from gen_screen import write_if_changed  # noqa: E402
from stick import COLUMNS, nesp  # noqa: E402

ROOM = 0x4000 // COLUMNS        # lines that fit the ROM's ARTICLE area


def to_ascii(text):
    out = bytearray()
    for char in text:
        mapped = nesp.to_ascii(ord(char))
        out += b"?" if mapped is None else mapped
    return bytes(out)


def lay_out(text):
    """The lines of a text whose first line is its title, each COLUMNS tile
    numbers."""
    title, _, body = text.partition("\n")
    wrap = nesp.Wrap(COLUMNS)
    wrap.title(to_ascii(title.strip()))
    wrap.put(to_ascii(body))
    wrap.close()
    return wrap.lines


def main(argv):
    with open(argv[1], encoding="utf-8") as handle:
        lines = lay_out(handle.read())
    if len(lines) > ROOM:
        sys.exit("%s is %d lines, and the ROM has room for %d" % (argv[1], len(lines), ROOM))
    out_dir = argv[2]
    os.makedirs(out_dir, exist_ok=True)
    write_if_changed(os.path.join(out_dir, "article.bin"), b"".join(lines))
    write_if_changed(os.path.join(out_dir, "article.inc"),
                     ("; Generated by tools/embed_article.py. Do not edit.\n"
                      "ARTICLE_LINES = %d\n" % len(lines)).encode("ascii"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
