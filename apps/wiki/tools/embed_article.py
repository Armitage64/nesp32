#!/usr/bin/env python3
"""Lay a text file out as the standalone ROM's built-in article.

    tools/embed_article.py nes/demo_article.txt build

Writes article.bin, lines of COLUMNS tile numbers exactly as the Stick
would serve them, and article.inc with their count. The file's first line
is the article's title; the rest is laid out by the Stick's own code
(neswiki.wrap), with "== Heading ==" lines for headings.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "firmware", "stick"))
sys.path.insert(0, HERE)

from gen_screen import write_if_changed  # noqa: E402
from neswiki import wikitext  # noqa: E402
from neswiki.linkrate import COLUMNS  # noqa: E402
from neswiki.wrap import Article, Wrapper  # noqa: E402

ROOM = 0x4000 // COLUMNS        # lines that fit the ROM's ARTICLE area


def to_ascii(text):
    out = bytearray()
    for char in text:
        out += wikitext.to_ascii(ord(char)) or b"?"
    return bytes(out)


def lay_out(text, capacity=ROOM):
    """An Article from a text whose first line is its title."""
    title, _, body = text.partition("\n")
    article = Article(capacity)
    wrapper = Wrapper(article)
    wrapper.title(to_ascii(title.strip()))
    wrapper.put(to_ascii(body))
    wrapper.close()
    return article


def main(argv):
    with open(argv[1], encoding="utf-8") as handle:
        article = lay_out(handle.read())
    if article.full:
        sys.exit("%s is longer than the %d lines the ROM has room for" % (argv[1], ROOM))
    out_dir = argv[2]
    os.makedirs(out_dir, exist_ok=True)
    write_if_changed(os.path.join(out_dir, "article.bin"),
                     bytes(article.data[:article.count * COLUMNS]))
    write_if_changed(os.path.join(out_dir, "article.inc"),
                     ("; Generated by tools/embed_article.py. Do not edit.\n"
                      "ARTICLE_LINES = %d\n" % article.count).encode("ascii"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
