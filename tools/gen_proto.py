#!/usr/bin/env python3
"""Write the link's numbers for each side from proto/nesp.toml.

    tools/gen_proto.py build

    nesp_proto.h      for the Stick's firmware (C)
    nesp_proto.inc    for the console (ca65)
    nesp_proto.py     for the tools and the tests

The three hold the same names with the same values, so the two ends of the
link cannot disagree. A file is rewritten only if its contents changed.
"""

import os
import sys

try:
    import tomllib
except ImportError:                 # Python before 3.11
    try:
        import tomli as tomllib
    except ImportError:             # and no tomli: ESP-IDF's Python, perhaps
        tomllib = None

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "..", "proto", "nesp.toml")
PREFIX = "NESP_"


def load(path=SOURCE):
    if tomllib is None:
        return load_plainly(path)
    with open(path, "rb") as handle:
        return tomllib.load(handle)


def load_plainly(path):
    """The definition without a TOML library. It reads only what the file
    uses: [tables.with.dots], and names given whole numbers."""
    proto = {}
    table = proto
    with open(path) as handle:
        for line in handle:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if line.startswith("["):
                table = proto
                for part in line.strip("[]").split("."):
                    table = table.setdefault(part.strip(), {})
            else:
                name, value = (part.strip() for part in line.split("=", 1))
                table[name] = int(value, 0)
    return proto


def constants(proto):
    """Every (name, value) the definition gives, in its order, and with the
    numbers worked out from others."""
    out = []

    def add(name, value):
        if any(name == seen for seen, _ in out):
            raise ValueError("%s is defined twice" % name)
        out.append((name, value))

    link = proto["link"]
    for name, value in link.items():
        add(PREFIX + name, value)
    add(PREFIX + "BAUD", (link["CPU_HZ"] + link["PERIOD"] // 2) // link["PERIOD"])
    add(PREFIX + "FRAME_MAX", link["PAYLOAD_MAX"] + link["OVERHEAD"])
    for name, value in proto["status"].items():
        add(PREFIX + "ST_" + name, value)
    ids = {}
    for service, body in proto["services"].items():
        if body["id"] in ids:
            raise ValueError("%s and %s share an id" % (service, ids[body["id"]]))
        ids[body["id"]] = service
        add(PREFIX + "SVC_" + service, body["id"])
        for op, value in body.get("ops", {}).items():
            add(PREFIX + service + "_" + op, value)
    for enum, values in proto["enums"].items():
        for name, value in values.items():
            add(PREFIX + enum + "_" + name, value)
    for name, value in proto["sizes"].items():
        add(PREFIX + name, value)
    return out


def shown(name, value):
    """Small counts in decimal, everything else as the bytes it is."""
    if name.endswith(("_HZ", "_BAUD")) or name in (
            PREFIX + "PERIOD", PREFIX + "TO_NES_BITS", PREFIX + "TO_STICK_BITS",
            PREFIX + "HEADER", PREFIX + "OVERHEAD", PREFIX + "PAYLOAD_MAX",
            PREFIX + "FRAME_MAX", PREFIX + "REPLY_BEFORE_HELLO", PREFIX + "REPLY_MIN", PREFIX + "APP_ID",
            PREFIX + "PROTOCOL") or name.endswith(("_MAX", "_QUEUE", "_COLUMNS", "_EARLY", "_MS",
                                                   "_MIN", "_RATES")):
        return "%d" % value, "%d" % value
    if value > 0xFF:
        return "0x%04X" % value, "$%04X" % value
    return "0x%02X" % value, "$%02X" % value


NOTE = "Generated by tools/gen_proto.py from proto/nesp.toml. Do not edit."


def c_header(values):
    lines = ["/* %s */" % NOTE, "#ifndef NESP_PROTO_H", "#define NESP_PROTO_H", ""]
    lines += ["#define %-28s %s" % (name, shown(name, value)[0]) for name, value in values]
    lines += ["", "#endif"]
    return "\n".join(lines) + "\n"


def ca65_include(values):
    lines = ["; %s" % NOTE, ""]
    lines += ["%-28s = %s" % (name, shown(name, value)[1]) for name, value in values]
    return "\n".join(lines) + "\n"


def python_module(proto, values):
    lines = ['"""%s"""' % NOTE, ""]
    lines += ["%s = %s" % (name, shown(name, value)[0]) for name, value in values]
    lines += ["", "SERVICES = {"]
    lines += ["    0x%02X: %r," % (body["id"], service)
              for service, body in proto["services"].items()]
    lines += ["}"]
    return "\n".join(lines) + "\n"


def write_if_changed(path, text):
    data = text.encode("ascii")
    try:
        with open(path, "rb") as handle:
            if handle.read() == data:
                return
    except FileNotFoundError:
        pass
    with open(path, "wb") as handle:
        handle.write(data)


def main(argv):
    out = argv[1]
    proto = load()
    values = constants(proto)
    os.makedirs(out, exist_ok=True)
    write_if_changed(os.path.join(out, "nesp_proto.h"), c_header(values))
    write_if_changed(os.path.join(out, "nesp_proto.inc"), ca65_include(values))
    write_if_changed(os.path.join(out, "nesp_proto.py"), python_module(proto, values))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
